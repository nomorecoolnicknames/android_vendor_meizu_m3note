#!/bin/sh
# check_profile_files.sh — гейт файлов профиля ревизии, вызывается из profile-*.mk.
# Печатает НИЧЕГО, если каждый файл списка есть в каталоге-источнике и его
# sha256 совпадает; иначе — короткий маркер в stdout (makefile делает $(error))
# и подробности в stderr.
#
# Зачем: файлы, которые различаются между m681 и l681 (модем с RF-настройкой
# платы, патчи WMT, сенсорный стек), должны прийти ровно из проверенного
# источника. Рядом на диске лежит похожий, но ЧУЖОЙ сток a local tree
# (слой m91/Wingtech, модем V9.P60) — перепутать его со стоком L681H значит
# поставить l681 модем другой платы.
#
#   $1 — имя профиля (m681 | l681), только для сообщений
#   $2 — каталог-источник
#   $3 — список sha256 (формат sha256sum, пути относительно $2)
set -u
REV=$1
DIR=$2
LIST=$3

[ -d "$DIR" ] || {
    echo "КАТАЛОГ ИСТОЧНИКА ПРОФИЛЯ $REV НЕ НАЙДЕН: $DIR" >&2
    echo "profile-$REV: каталога источника нет, см. подробности выше"; exit 0; }
[ -f "$LIST" ] || { echo "НЕТ СПИСКА: $LIST" >&2; echo "profile-$REV: нет списка sha256, см. подробности выше"; exit 0; }

bad=0
tmp=$(mktemp) || { echo "profile-$REV: mktemp не сработал — гейт не может проверить файлы"; exit 0; }
grep -v '^#' "$LIST" | grep -v '^[[:space:]]*$' > "$tmp"
while read -r want rel; do
    f="$DIR/$rel"
    if [ ! -f "$f" ]; then
        echo "  НЕТ ФАЙЛА: $rel" >&2; bad=$((bad+1)); continue
    fi
    have=$(sha256sum "$f" | cut -d' ' -f1)
    if [ "$have" != "$want" ]; then
        echo "  ДРУГОЙ ФАЙЛ: $rel" >&2
        echo "    ожидаем $want" >&2
        echo "    найдено $have" >&2
        bad=$((bad+1))
    fi
done < "$tmp"
rm -f "$tmp"

[ "$bad" -eq 0 ] && exit 0
cat >&2 <<MSG
ФАЙЛЫ ПРОФИЛЯ $REV НЕ СОВПАЛИ СО СПИСКОМ ($bad шт.).
  каталог: $DIR
  список:  $LIST
Менять список можно только вместе с записью в README.md: откуда новые файлы
и какой захват подтвердил их на аппарате этой ревизии.
MSG
echo "profile-$REV: $bad файл(ов) не совпало, см. подробности выше"
